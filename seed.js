// items: { id: 항목 } (저장된 그대로). 돌려주는 값: patches(기존 항목 일부 수정), creates(새 항목), removes(지울 id)
export function planBagV3(items) {
  const seed = new Map();
  let order = 0;
  for (const g of BAG) for (const it of g.items) seed.set(it.id, { ...it, group: g.name, order: (order += 10) });
  const has = (id) => Object.prototype.hasOwnProperty.call(items, id);
  const untouched = (id) => has(id) && items[id].title === PREV_TITLE[id];
  const patches = [], creates = [], removes = [];

  for (const [id, it] of Object.entries(items)) {
    if (it.list !== "bag") continue;
    const s = seed.get(id);
    if (s) {
      const p = { group: s.group, order: s.order, when: s.w || "" };
      if (s.a && (it.assignee || "both") === "both") p.assignee = s.a;
      if (PREV_TITLE[id] !== undefined && untouched(id)) { p.title = s.t; p.note = s.n || ""; }
      // 퇴원 겉옷(bag-x3)을 퇴소 옷(bag-c9)에 합쳐요: 둘 다 챙겼을 때만 체크된 상태로
      if (id === "bag-c9" && untouched("bag-c9") && untouched("bag-x3") && it.done && !items["bag-x3"].done) {
        Object.assign(p, { done: false, doneBy: "", doneAt: 0 });
      }
      patches.push([id, p]);
    } else if (id === "bag-x3" && untouched(id) && untouched("bag-c9")) {
      removes.push(id);
    } else {
      const g = V3_GROUP[GROUP_RENAME[it.group] || it.group];
      if (g && g !== it.group) patches.push([id, { group: g }]);
    }
  }
  // 수유패드는 병원(bag-h9)·조리원(bag-c3) 묶음에 하나씩 있었어요 → 새 항목 하나로. 두 묶음을 다 챙겼으면 체크된 상태로 시작해요.
  if (!has("bag-n1")) {
    const s = seed.get("bag-n1");
    const a = items["bag-h9"], b = items["bag-c3"];
    const done = !!(a && b && a.done && b.done);
    creates.push(["bag-n1", {
      list: "bag", group: s.group, title: s.t, note: s.n || "", link: "", offset: null, when: s.w,
      assignee: "both", order: s.order, done,
      doneBy: done ? (a.doneBy || "") : "", doneAt: done ? Math.max(a.doneAt || 0, b.doneAt || 0) : 0,
    }]);
  }
  return { patches, creates, removes };
}

